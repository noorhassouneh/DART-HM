void main() {
  double mark1 = 70;

  switch (mark1) {
    case 90:
      print('A');
      break;
    case 80:
      print('B');
      break;
    case 70:
      print('C');
      break;
    case 60:
      print('D');
      break;
    case 50:
      print('F');
      break;
    default:
      print('Invalid mark');
  }
}